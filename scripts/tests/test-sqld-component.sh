  internal-sqld-verify-sha256)
    shift
    [ "${1:-}" = --file ] && file="$2" && shift 2
    [ "${1:-}" = --expected-sha256 ] && expected="$2" && shift 2
    [ "${1:-}" = --expected-mode ] && expected_mode="$2" && shift 2
    [ "$#" = 0 ]
    [ -f "$file" ] && [ ! -L "$file" ]
    [ "0$(stat -c '%a' "$file")" = "$expected_mode" ]
    printf 'rust-verify\t%s\t%s\n' "$expected" "$file" >>"${SQLD_SHA_LOG:?}"
    [ "${SQLD_CHECKSUM_FAIL:-0}" = 0 ]
    case "$expected_mode" in
      0600) cmp -s "$file" "${SQLD_FIXTURE_ARCHIVE:?}" ;;
      0755) cmp -s "$file" "${SQLD_FIXTURE_PAYLOAD:?}" ;;
      *) exit 2 ;;
    esac
    ;;
  internal-sqld-readiness-probe)
    [ -z "${SQLD_PROBE_LOG:-}" ] || printf '%s\n' "$*" >>"$SQLD_PROBE_LOG"
    shift
    pid=""
    expected=""
    port=""
    token_file=""
    helper_digest=""
    timeout=""
    while [ "$#" -gt 0 ]; do
