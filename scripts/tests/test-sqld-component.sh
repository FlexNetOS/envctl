    fingerprint_inputs=()
    for path in "${toolchain_files[@]}"; do fingerprint_inputs+=("F:$path"); done
    for path in "${toolchain_roots[@]}"; do fingerprint_inputs+=("R:$path"); done
    for path in "${crate_archives[@]}"; do fingerprint_inputs+=("A:$path"); done
