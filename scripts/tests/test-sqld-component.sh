auth_token_sentinel='secret.jwt.token-sentinel'
mkdir -p "$meta/.config/systemd/user" "$meta/var/lib/sqld" "$fake_bin" "$shadow_bin" \
  "$lifecycle_shadow_bin" "$fixture" "$auth_source"
