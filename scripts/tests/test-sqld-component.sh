    chmod 0600 "$output"
    ;;
  internal-sqld-verify-source-digest)
    shift
    [ "${1:-}" = --source-root ] && source_root="$2" && shift 2
    toolchain_files=()
    toolchain_roots=()
    crate_archives=()
    while [ "${1:-}" = --toolchain-file ]; do
      toolchain_files+=("$2")
      shift 2
    done
    while [ "${1:-}" = --toolchain-root ]; do
      toolchain_roots+=("$2")
      shift 2
    done
    while [ "${1:-}" = --crate-archive ]; do
      crate_archives+=("$2")
      shift 2
    done
    [ "${1:-}" = --digest ] && digest="$2" && shift 2
    [ "$#" = 0 ] && [ -f "$digest" ] && [ ! -L "$digest" ] && [ "$(stat -c '%a' "$digest")" = 600 ]
    [ "${#toolchain_files[@]}" -gt 0 ] && [ "${#toolchain_roots[@]}" -gt 0 ] \
