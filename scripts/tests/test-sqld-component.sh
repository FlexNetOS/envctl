printf 'preserve durable data\n' >"$meta/var/lib/sqld/data-marker"
printf '%s\n' "$auth_key_sentinel" >"$auth_key_source"
printf '%s\n' "$auth_token_sentinel" >"$auth_token_source"
chmod 0600 "$auth_key_source" "$auth_token_source"

cat >"$fixture/sqld" <<'SH'
