#!/usr/bin/env bash
set -euo pipefail
file_digest() { /usr/bin/sha256sum "$1" | awk '{print $1}'; }
verify_digest_record() {
  file="$1"
  digest_file="$2"
  [ -f "$file" ] && [ ! -L "$file" ] && [ "$(stat -c '%a' "$file")" = 755 ]
  [ -f "$digest_file" ] && [ ! -L "$digest_file" ] && [ "$(stat -c '%a' "$digest_file")" = 600 ]
  IFS='  ' read -r expected recorded <"$digest_file"
  [ -n "$expected" ] && [ "$(readlink -f "$recorded")" = "$(readlink -f "$file")" ]
  [ "$(file_digest "$file")" = "$expected" ]
}
source_fingerprint() {
  source_root="$1"
  shift
  (
    cd "$source_root"
    inputs=(Cargo.toml Cargo.lock rust-toolchain.toml assets/scripts/envctl-sqld-hermetic-cargo.sh crates/secretctl crates/secrets-engine crates/secrets-proto)
    [ ! -f .cargo/config.toml ] || inputs+=(.cargo/config.toml)
    [ ! -f .cargo/config ] || inputs+=(.cargo/config)
    find "${inputs[@]}" \
      -type f \( -name '*.rs' -o -name '*.toml' -o -name '*.proto' -o -name '*.sh' -o -name Cargo.lock \) -print0 \
      | LC_ALL=C sort -z \
      | xargs -0 /usr/bin/sha256sum \
      | /usr/bin/sha256sum
    for build_input in "$@"; do
      kind="${build_input%%:*}"
      path="${build_input#?:}"
      case "$kind" in
        F|A)
          printf '%s  %s\n' "$(basename "$path")" "$(/usr/bin/sha256sum "$path" | awk '{print $1}')"
          ;;
        R)
          printf 'root:%s\n' "$(basename "$path")"
          (
            cd "$path"
            while IFS= read -r -d '' node; do
              mode="$(stat -c '%a' -- "$node")"
              if [ -L "$node" ]; then
                printf 'l\0%s\0%s\0%s\0' "${node#./}" "$mode" "$(readlink -- "$node")"
              elif [ -d "$node" ]; then
                printf 'd\0%s\0%s\0' "${node#./}" "$mode"
              elif [ -f "$node" ]; then
                printf 'f\0%s\0%s\0%s\0' "${node#./}" "$mode" \
                  "$(/usr/bin/sha256sum "$node" | awk '{print $1}')"
              else
                exit 2
              fi
            done < <(find . -mindepth 1 -print0 | LC_ALL=C sort -z)
          )
          ;;
        *) exit 2 ;;
      esac
    done | LC_ALL=C sort
  ) | /usr/bin/sha256sum | awk '{print $1}'
}
