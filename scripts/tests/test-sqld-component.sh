# Optional real-binary probe used by the release-pin verification lane. It exercises the actual
# pinned sqld parser/verifier with material emitted by the built secretctl command; the default
# hermetic test remains network- and port-free.
if [ -n "${SQLD_REAL_BIN:-}" ]; then
  [ -x "$SQLD_REAL_BIN" ] || fail "SQLD_REAL_BIN is not executable"
  [ -x "${SQLD_REAL_SECRETCTL_BIN:-}" ] || fail "SQLD_REAL_SECRETCTL_BIN is not executable"
  (
    set -euo pipefail
    real_dir="$tmp/real-auth-probe"
    real_port="${SQLD_REAL_PORT:-18082}"
    mkdir -p "$real_dir/db"
    "$SQLD_REAL_SECRETCTL_BIN" internal-sqld-auth-bootstrap \
      --public-key "$real_dir/auth-jwt-key.pem" --client-token "$real_dir/client.jwt"
    "$SQLD_REAL_BIN" --http-listen-addr "127.0.0.1:$real_port" \
      --auth-jwt-key-file "$real_dir/auth-jwt-key.pem" -d "$real_dir/db" \
      >"$real_dir/sqld.log" 2>&1 &
    sqld_pid=$!
    trap 'kill "$sqld_pid" 2>/dev/null || true; wait "$sqld_pid" 2>/dev/null || true' EXIT
    ready=0
    for _ in $(seq 1 100); do
      if /usr/bin/curl --fail --silent --max-time 1 "http://127.0.0.1:$real_port/health" >/dev/null 2>&1; then
        ready=1
        break
      fi
      sleep 0.05
    done
    [ "$ready" = 1 ] || { cat "$real_dir/sqld.log" >&2; fail "real pinned sqld did not become ready"; }
    "$SQLD_REAL_SECRETCTL_BIN" internal-sqld-self-digest \
      --output "$real_dir/secretctl.sha256"
    "$SQLD_REAL_SECRETCTL_BIN" internal-sqld-readiness-probe \
      --pid "$sqld_pid" --expected-executable "$SQLD_REAL_BIN" --port "$real_port" \
      --client-token "$real_dir/client.jwt" --helper-digest "$real_dir/secretctl.sha256" \
      --timeout-seconds 5 \
      || fail "real pinned sqld failed the Rust-native MainPID/auth readiness barrier"
  )
fi

